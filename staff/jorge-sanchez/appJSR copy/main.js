var body = document.body // Se crea la variable para apuntar al body del document.
var title = document.createElement('h1') // Se crea un elemento <h1></h1> en el documento.
body.appendChild(title) // Al body, se le añade un nodo hijo, que es el título <h1></h1> creado 
title.innerText = 'Hola, App!' // Se introduce texto en el elemento <h1></h1>, que es "Hola, App!"




